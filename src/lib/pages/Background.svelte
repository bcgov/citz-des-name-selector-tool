        The transition to include Indigenous language person names in B.C.
        government systems will take many years.
    </p>

    <p>
        Government is consulting Indigenous Peoples regarding an interim
        solution that will include developing an <strong
            >alternate spelling</strong
        > of an Indigenous language name using English alphabet characters. This alternate
        spelling will be used in systems that are not yet able to accommodate Indigenous
        characters.
    </p>

    <p>
        The alternate spelling will adhere to the constraints in existing
        systems and can be displayed on identification to support people safely
        accessing services until these connected systems are successfully
        updated.
    </p>
